"""Turn a `pip install --dry-run --report` into a hash-pinned requirements file.

Run on the runner's own platform (markers are evaluated against the host, so a
Linux lock cannot be resolved on Windows). harness-bench.yml installs from the
result with `--require-hashes --only-binary=:all: --no-deps`, so the paid run
installs exactly what the free probe resolved, and nothing builds from source.

    python bench/probes/lock.py REPORT.json OUT.txt
"""

from __future__ import annotations

import json
import sys


def main(report_path: str, out_path: str) -> int:
    report = json.load(open(report_path, encoding="utf-8"))
    lines = []
    for item in sorted(report["install"], key=lambda i: i["metadata"]["name"].lower()):
        name, version = item["metadata"]["name"], item["metadata"]["version"]
        hashes = (item.get("download_info", {}).get("archive_info", {}) or {}).get("hashes", {})
        if "sha256" not in hashes:
            print(f"no sha256 for {name}=={version}; refusing to write an unhashed lock", file=sys.stderr)
            return 1
        lines.append(f"{name}=={version} --hash=sha256:{hashes['sha256']}")
    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("# Generated by bench/probes/lock.py from a pip dry-run report on ubuntu-latest. Do not edit.\n")
        handle.write("\n".join(lines) + "\n")
    print(f"{len(lines)} pinned packages -> {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(*sys.argv[1:3]))
